#!/usr/bin/env node
// Renders the approved horizontal logo (public/brand/logo-horizontal.svg, proposed D-061) to a 3x transparent PNG for
// email, where SVG doesn't render, and writes it as base64 to lib/email-logo.ts. The emails embed it inline (CID), so it
// shows even while the site is behind Vercel login. Rerun after any logo change:
//
//   npm run email:logo
import { chromium } from "@playwright/test";
import { readFileSync, writeFileSync } from "node:fs";

const WIDTH = 220; // display width in the email, CSS px
const svg = readFileSync(new URL("../public/brand/logo-horizontal.svg", import.meta.url), "utf8");
const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 3, viewport: { width: WIDTH + 20, height: 80 } });
await page.setContent(`<body style="margin:0"><div id="l" style="width:${WIDTH}px;display:inline-block">${svg.replace("<svg ", `<svg style="width:${WIDTH}px;height:auto;display:block" `)}</div></body>`);
const png = await page.locator("#l").screenshot({ omitBackground: true });
const box = await page.locator("#l").boundingBox();
await browser.close();
writeFileSync(
  new URL("../lib/email-logo.ts", import.meta.url),
  `// Generated by scripts/email-logo.mjs from public/brand/logo-horizontal.svg. Do not edit by hand.\n` +
    `export const EMAIL_LOGO = { width: ${WIDTH}, height: ${Math.round(box.height)}, base64: "${png.toString("base64")}" } as const;\n`,
);
console.log(`lib/email-logo.ts: ${png.length} bytes, ${WIDTH}x${Math.round(box.height)} CSS px`);
